package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"text/template"

	contracts "github.com/haihhhhh/ht_server_frame/protocol"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
)

// 生成器和覆盖检查共用同一署名，便于识别本工具生成的 Go 和 JSON 文件。
const (
	generatorName     = "ht-protocol"
	generatedGoHeader = "// Code generated by " + generatorName + ". DO NOT EDIT."
)

// 消息编号的高、低两个字节分别存放分组和组内消息编号；两个字段都从 1 开始。
const idsPerGroup = 1 << 8

type generationMarker struct {
	GeneratedBy string `json:"generated_by"`
}

// 让 protoc 解析语法和导入；此处只读取官方描述数据，不另写 proto 文本解析器。
func buildCatalog(protoc, schema, root string, files []string, rpc bool, forward string) (map[string][]byte, error) {
	temp, err := os.MkdirTemp("", generatorName+"-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(temp)
	descriptor := filepath.Join(temp, "protocol.pb")
	args := []string{"--proto_path=" + schema, "--include_imports", "--descriptor_set_out=" + descriptor}
	if _, err = output(protoc, append(args, files...)...); err != nil {
		return nil, err
	}
	data, err := os.ReadFile(descriptor)
	if err != nil {
		return nil, err
	}
	var set descriptorpb.FileDescriptorSet
	if err = proto.Unmarshal(data, &set); err != nil {
		return nil, err
	}
	messages := map[string]*descriptorpb.DescriptorProto{}
	owners := map[string]*descriptorpb.FileDescriptorProto{}
	var index func(string, []*descriptorpb.DescriptorProto, *descriptorpb.FileDescriptorProto)
	index = func(prefix string, list []*descriptorpb.DescriptorProto, file *descriptorpb.FileDescriptorProto) {
		for _, m := range list {
			name := prefix + m.GetName()
			messages[name] = m
			owners[name] = file
			index(name+".", m.NestedType, file)
		}
	}
	for _, file := range set.File {
		prefix := ""
		if file.GetPackage() != "" {
			prefix = file.GetPackage() + "."
		}
		index(prefix, file.MessageType, file)
	}
	catalog := messages[root]
	if catalog == nil {
		return nil, fmt.Errorf("协议目录消息不存在：%s", root)
	}
	def := contracts.Definition{}
	for _, groupField := range catalog.Field {
		if err := directoryField(groupField); err != nil {
			return nil, err
		}
		group := messages[strings.TrimPrefix(groupField.GetTypeName(), ".")]
		if group == nil || group.GetOptions().GetMapEntry() {
			return nil, fmt.Errorf("无效协议分组：%s", groupField.GetName())
		}
		for _, field := range group.Field {
			if err := directoryField(field); err != nil {
				return nil, err
			}
			name := strings.TrimPrefix(field.GetTypeName(), ".")
			if messages[name] == nil || messages[name].GetOptions().GetMapEntry() {
				return nil, fmt.Errorf("无效消息类型：%s", name)
			}
			def.Messages = append(def.Messages, contracts.Message{
				ID:   uint16(groupField.GetNumber()*idsPerGroup + field.GetNumber()),
				Name: name,
			})
		}
	}
	if len(def.Messages) == 0 {
		return nil, fmt.Errorf("协议目录为空：%s", root)
	}
	sources := map[string]bool{}
	for _, file := range files {
		sources[filepath.Base(file)] = true
	}
	for _, file := range set.File {
		if !sources[file.GetName()] {
			continue
		}
		for _, service := range file.Service {
			for _, method := range service.Method {
				if method.GetClientStreaming() || method.GetServerStreaming() {
					return nil, fmt.Errorf("不支持流式接口：%s.%s", service.GetName(), method.GetName())
				}
				def.Methods = append(def.Methods, contracts.Method{
					Service:  service.GetName(),
					Name:     method.GetName(),
					Request:  strings.TrimPrefix(method.GetInputType(), "."),
					Response: strings.TrimPrefix(method.GetOutputType(), "."),
				})
			}
		}
	}
	if _, err = contracts.New(def); err != nil {
		return nil, err
	}
	sort.Slice(def.Messages, func(i, j int) bool { return def.Messages[i].ID < def.Messages[j].ID })
	sort.Slice(def.Methods, func(i, j int) bool {
		return def.Methods[i].Service+"."+def.Methods[i].Name < def.Methods[j].Service+"."+def.Methods[j].Name
	})
	goPackage := owners[root].GetOptions().GetGoPackage()
	packageName := filepath.Base(goPackage)
	if _, name, ok := strings.Cut(goPackage, ";"); ok {
		packageName = name
	}
	if !token.IsIdentifier(packageName) || token.Lookup(packageName).IsKeyword() {
		return nil, fmt.Errorf("目录消息必须声明有效的 go_package：%s", root)
	}
	layout, err := template.ParseFS(templateFiles, "templates/catalog.go.tmpl")
	if err != nil {
		return nil, err
	}
	var source bytes.Buffer
	if err = layout.Execute(&source, struct {
		Header     string
		Package    string
		Definition contracts.Definition
	}{
		Header:     generatedGoHeader,
		Package:    packageName,
		Definition: def,
	}); err != nil {
		return nil, err
	}
	goData, err := format.Source(source.Bytes())
	if err != nil {
		return nil, err
	}
	jsonData, err := json.MarshalIndent(struct {
		generationMarker
		contracts.Definition
	}{
		generationMarker: generationMarker{GeneratedBy: generatorName},
		Definition:       def,
	}, "", "  ")
	if err != nil {
		return nil, err
	}
	result := map[string][]byte{"catalog.gen.go": goData, "catalog.json": append(jsonData, '\n')}
	if rpc {
		var inputs []string
		for _, file := range files {
			inputs = append(inputs, filepath.Base(file))
		}
		rpcData, err := generateRPC(&set, inputs, owners[root], forward)
		if err != nil {
			return nil, err
		}
		result[rpcFileName] = rpcData
	}
	return result, nil
}

func directoryField(field *descriptorpb.FieldDescriptorProto) error {
	if field.GetNumber() < 1 || field.GetNumber() >= idsPerGroup || field.GetType() != descriptorpb.FieldDescriptorProto_TYPE_MESSAGE || field.GetLabel() == descriptorpb.FieldDescriptorProto_LABEL_REPEATED || field.OneofIndex != nil {
		return fmt.Errorf("协议目录字段 %s 必须为编号 1—255 的普通消息字段", field.GetName())
	}
	return nil
}

func checkCatalogTarget(path string) error {
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		return err
	}
	if strings.HasSuffix(path, ".go") && strings.HasPrefix(string(data), generatedGoHeader+"\n") {
		return nil
	}
	if strings.HasSuffix(path, ".json") {
		var marker generationMarker
		if json.Unmarshal(data, &marker) == nil && marker.GeneratedBy == generatorName {
			return nil
		}
	}
	return fmt.Errorf("拒绝覆盖非生成文件：%s", path)
}
