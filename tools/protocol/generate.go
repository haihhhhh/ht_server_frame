package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

type generationOptions struct {
	schema      string
	destination string
	catalogName string
	rpc         bool
	forward     string
}

func generateProtocol(tools toolPaths, options generationOptions) error {
	if err := checkVersion(tools.protoc, protocVersionOutput); err != nil {
		return err
	}
	if err := checkVersion(tools.plugin, pluginVersionOutput); err != nil {
		return err
	}
	schema := options.schema
	files, err := filepath.Glob(filepath.Join(schema, "*.proto"))
	if err != nil {
		return err
	}
	if len(files) == 0 {
		return fmt.Errorf("未找到协议定义：%s", schema)
	}
	destination := options.destination
	// 不再请求辅助代码时清除旧生成文件，避免删除接口后残留过期调用。
	rpcPath := filepath.Join(destination, rpcFileName)
	if err := checkCatalogTarget(rpcPath); err != nil {
		return err
	}
	catalogFiles, err := buildCatalog(tools.protoc, schema, options.catalogName, files, options.rpc, options.forward)
	if err != nil {
		return err
	}
	for name := range catalogFiles {
		if err := checkCatalogTarget(filepath.Join(destination, name)); err != nil {
			return err
		}
	}
	if err := os.MkdirAll(destination, 0755); err != nil {
		return err
	}
	for _, file := range files {
		target := filepath.Join(destination, strings.TrimSuffix(filepath.Base(file), ".proto")+".pb.go")
		data, err := os.ReadFile(target)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if err == nil && !strings.HasPrefix(string(data), "// Code generated by protoc-gen-go. DO NOT EDIT.") {
			return fmt.Errorf("拒绝覆盖非生成文件：%s", target)
		}
	}
	args := []string{"--proto_path=" + schema, "--plugin=protoc-gen-go=" + tools.plugin, "--go_out=" + destination, "--go_opt=paths=source_relative"}
	if _, err := output(tools.protoc, append(args, files...)...); err != nil {
		return err
	}
	// 保留生成标记及版本信息，仅统一固定生成器的说明性注释。
	replacer := strings.NewReplacer(
		"Verify that this generated code is sufficiently up-to-date.", "检查生成代码是否满足最低版本要求。",
		"Verify that runtime/protoimpl is sufficiently up-to-date.", "检查运行库是否满足最低版本要求。",
		"is the sub-list for", "对应的索引子列表：",
	)
	deprecated := regexp.MustCompile(`Deprecated: Use (.+) instead\.`)
	for _, file := range files {
		path := filepath.Join(destination, strings.TrimSuffix(filepath.Base(file), ".proto")+".pb.go")
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		text := deprecated.ReplaceAllString(replacer.Replace(string(data)), "Deprecated: 请改用 $1。")
		if err := os.WriteFile(path, []byte(text), 0644); err != nil {
			return err
		}
	}
	for name, data := range catalogFiles {
		if err := os.WriteFile(filepath.Join(destination, name), data, 0644); err != nil {
			return err
		}
	}
	if !options.rpc {
		if err := os.Remove(rpcPath); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	fmt.Printf("协议与编号目录已生成到 %s；产物不入库，请提交协议定义和工具变更。\n", destination)
	return nil
}
